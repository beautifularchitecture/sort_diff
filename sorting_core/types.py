"""Data model for the sorting core.

Plain dataclasses only: no I/O, no markup, no behaviour beyond a counter
reset (SD-1, SD-3, SD-4). The entity model is documented in
``construction/sorting-core/functional-design/entities.md``.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class SortInput:
    """One normalized set of strings to be sorted (BR-INP-3).

    ``run_id`` is generated by :class:`InputProcessor.normalize` and is
    immutable for the lifetime of the object. The lists are exposed as
    plain lists but are never mutated by the core.
    """

    run_id: str
    raw_entries: list[str]
    normalized_strings: list[str]


@dataclass(frozen=True)
class AlgorithmResult:
    """Output of one sorting algorithm on one ``SortInput``.

    ``comparisons`` is the primary, cross-algorithm comparable step metric
    (BR-SE-1); ``swaps`` is algorithm-specific and secondary (BR-SE-2).
    """

    run_id: str
    algorithm: str
    sorted_strings: list[str]
    comparisons: int
    swaps: int


@dataclass(frozen=True)
class AccuracyCheck:
    """Verification result for one ``AlgorithmResult`` (BR-AC-1)."""

    run_id: str
    algorithm: str
    passed: bool


@dataclass
class Counter:
    """Shared comparison/swap counter (NFR design Q3, option A).

    One instance is created per ``SortingEngine.run_all`` call and passed
    into each algorithm; it is reset between algorithms so each
    ``AlgorithmResult`` carries only its own counts.
    """

    comparisons: int = 0
    swaps: int = 0

    def reset(self) -> None:
        """Zero both counts before the next algorithm runs."""
        self.comparisons = 0
        self.swaps = 0


__all__ = ["AccuracyCheck", "AlgorithmResult", "Counter", "SortInput"]
